// The mapping builder: a Builder (builder.js) that records when mappings
// are asked for. Each mark closes into one MappingStore row,
//
//   { nodeId, role, mappingKind, sourceStart, sourceEnd,
//     generatedStart, generatedEnd, fileId }
//
// with both spans known by construction, never found by searching the
// output. The source span is the node's NodeStore span for '$self', its
// RoleStore span for any other role, a zero-width anchor at the node's
// start for a literal-sourced role (mappingKind 'synthetic'), or the
// caller's for a markSpan role. The kind is decided, never declared:
// 'exact' when the emitted text equals the source slice, 'cover'
// otherwise. Serializing rows into a source map is src/sourcemap.js's.
//
// The open frames keep their spans whether or not rows are recorded:
// a positioned rejection reads the innermost one (currentMark), and on
// the TS face a schema's descriptor word claims its own source
// occurrence inside it (claimWord).

import { IDENT_PART, isIdentifierName } from '../ident.js';
import { counter } from '../counter.js';
import { Builder, spanRole } from './builder.js';

// The roles whose emission normalizes whitespace by design (the face
// renders annotation text through normalizeTypeText): a cover frame of
// one of these that differs from its source only in whitespace runs
// records an exact row per non-space segment, so the reads inside an
// aligned annotation keep their own rows.
const NORMALIZED_ROLES = new Set(['annotation', 'returnType']);

export class MappingBuilder extends Builder {
  // `record`: record the rows (a builder that records none still keeps
  // each frame's spans, which a positioned rejection reads). `leaves`:
  // record a row for each leaf a lowering emits (the TS face, whose
  // editor reads a name's own occurrence). `claims`: keep the source
  // spans that own an exact row, which claimWord consults.
  constructor(stores, source = null, { record = true, leaves = false, claims = false } = {}) {
    super();
    this.stores = stores;
    this.source = source;
    this.record = record;
    this.leaves = leaves;
    this.rows = [];
    this.trackExact = claims;
    this.exactSourceSpans = new Set();
    // An echo emission (a replayed line) maps nothing.
    this.suppressClaims = false;
    // Exactness memo by alignment delta (sourceStart − generatedStart):
    // the last generated range verified against the source at that
    // delta, with its chunk bounds. Nested exact frames share a delta, so
    // an enclosing frame compares only the chunks outside the memo's
    // range: every generated byte is compared once, not once per
    // enclosing frame, keeping deep chains linear.
    this.exact = new Map();
  }

  // Frames here are objects: the mark's spans, kind, and where its
  // output starts.
  get frameNode() {
    const f = this.frames;
    return f.length === 0 ? null : f[f.length - 1].nodeId;
  }

  get currentMark() {
    const f = this.frames;
    return f.length === 0 ? null : f[f.length - 1];
  }

  beginMark(nodeId, role) {
    if (role === '$self') {
      const n = this.stores.node(nodeId);
      this.openFrame(nodeId, role, n.sourceStart, n.sourceEnd, null);
      return;
    }
    const r = this.stores.role(nodeId, role);
    if ('literal' in r) {
      const at = this.stores.node(nodeId).sourceStart;
      this.openFrame(nodeId, role, at, at, 'synthetic');
    } else {
      this.openFrame(nodeId, role, r.sourceStart, r.sourceEnd, null);
    }
  }

  markSpan(nodeId, role, sourceStart, sourceEnd, fn) {
    this.beginSpan(nodeId, role, sourceStart, sourceEnd);
    fn();
    this.endMark();
  }

  beginSpan(nodeId, role, sourceStart, sourceEnd) {
    spanRole(role);
    this.openFrame(nodeId, role, sourceStart, sourceEnd, null);
  }

  // `kind` is null when endMark decides it from the emitted text.
  openFrame(nodeId, role, sourceStart, sourceEnd, kind) {
    this.frames.push({ nodeId, role, sourceStart, sourceEnd, kind, generatedStart: this.length, chunkStart: this.chunks.length });
  }

  endMark() {
    const f = this.frames.pop();
    if (!this.record) return;
    const first = this.rows.length;
    let kind = f.kind;
    if (kind === null) {
      kind = this.matches(f) ? 'exact' : 'cover';
      if (kind === 'cover' && NORMALIZED_ROLES.has(f.role)) this.layoutTwin(f);
    }
    this.rows.push({
      nodeId: f.nodeId, role: f.role, mappingKind: kind,
      sourceStart: f.sourceStart, sourceEnd: f.sourceEnd,
      generatedStart: f.generatedStart, generatedEnd: this.length,
      fileId: 0,
    });
    if (this.trackExact) {
      for (let i = first; i < this.rows.length; i++) {
        const r = this.rows[i];
        if (r.mappingKind === 'exact') this.exactSourceSpans.add(`${r.sourceStart}:${r.sourceEnd}`);
      }
    }
  }

  // Claim the next occurrence of a word inside the current mark, from
  // `occurrences` (the source spans the lexer recorded for that spelling,
  // in source order): a schema's descriptor text is generated, and its
  // words are no leaves. A fresh mark frame restarts the cursor, which is
  // what one source role emitted into several generated regions needs. No
  // generated text is searched: emission order chooses among repeats.
  claimWord(value, occurrences) {
    const f = this.currentMark;
    if (f === null || this.suppressClaims || occurrences === undefined) return null;
    const candidates = occurrences.filter((p) => p.sourceStart >= f.sourceStart && p.sourceEnd <= f.sourceEnd);
    if (candidates.length === 0) return null;
    // An occurrence that already owns an exact row was placed by a
    // narrower role, so a broad frame must not re-place it; one this frame
    // already handed out must not go twice. What survives is taken in
    // source order. The frame's record is a SET: the eligible list shrinks
    // as claims register their rows, so a call count would walk off it.
    const claims = f.wordClaims ?? (f.wordClaims = new Map());
    let taken = claims.get(value);
    if (taken === undefined) claims.set(value, taken = new Set());
    const free = candidates.filter((c) => !taken.has(c.sourceStart));
    const unplaced = free.filter((c) => !this.exactSourceSpans.has(`${c.sourceStart}:${c.sourceEnd}`));
    let p = (unplaced.length > 0 ? unplaced : free)[0];
    // Every occurrence in this frame is spoken for: a further emission of
    // the word re-reads the bytes it already placed, and maps to the
    // occurrence most recently placed — in this frame, else by an earlier
    // one. A frame that placed nothing declines.
    if (p === undefined) {
      const last = [...taken].pop();
      p = last === undefined ? undefined : candidates.find((c) => c.sourceStart === last);
      if (p === undefined) {
        const placed = candidates.filter((c) => this.exactSourceSpans.has(`${c.sourceStart}:${c.sourceEnd}`));
        p = placed[placed.length - 1];
      }
      if (p === undefined) return null;
    }
    taken.add(p.sourceStart);
    return [p.sourceStart, p.sourceEnd];
  }

  // A leaf's row, under the innermost frame's node: 'identifier' for a
  // name, 'literal' for any other spelling. A token that carries a sigil
  // (the symbol `:alpha`) spans the sigil too; the name's own bytes are
  // the span's tail. Outside every frame, on a builder that maps no
  // leaves, or with no source text, a leaf is plain text.
  leaf(leafId, text) {
    if (!this.leaves || this.frames.length === 0 || this.source === null) {
      this.emit(text);
      return;
    }
    const n = this.stores.node(leafId);
    let { sourceStart, sourceEnd } = n;
    const spelled = this.source.slice(sourceStart, sourceEnd);
    if (spelled !== text && spelled.endsWith(text) && !IDENT_PART.test(spelled[spelled.length - text.length - 1] ?? '')) {
      sourceStart = sourceEnd - text.length;
    }
    this.beginSpan(this.frameNode, isIdentifierName(text) ? 'identifier' : 'literal', sourceStart, sourceEnd);
    this.emit(text);
    this.endMark();
  }

  // The memo's chunk bounds name the old numbering.
  renumbered() {
    this.exact.clear();
  }

  // Does the text emitted during frame `f` equal its source span? The
  // length gate answers most covers at once, the chunk walk stops at the
  // first mismatching chunk, and the memo lets an enclosing frame skip
  // every chunk a contained exact frame verified.
  matches(f) {
    const src = this.source;
    if (src === null) return false;
    // The length gate reads the span's nominal width, so it equals a
    // slice comparison only for in-range spans; an out-of-range span is
    // a store-protocol violation, never something to clamp over.
    if (f.sourceStart < 0 || f.sourceEnd > src.length) {
      throw new Error(
        `builder: mark (nodeId ${f.nodeId}, role '${f.role}') has source span ` +
        `[${f.sourceStart}, ${f.sourceEnd}) outside the source text ` +
        `[0, ${src.length}) — store-protocol violation`,
      );
    }
    const genEnd = this.length;
    if (genEnd - f.generatedStart !== f.sourceEnd - f.sourceStart) return false;
    const delta = f.sourceStart - f.generatedStart;
    const m = this.exact.get(delta);
    // The memo may begin before this frame (an earlier sibling at the
    // same delta bridged in): any part of it inside the frame is verified.
    const skippable = m !== undefined && m.genEnd <= genEnd;
    const chunks = this.chunks;
    const chunkEnd = chunks.length;
    let pos = f.generatedStart;
    let i = f.chunkStart;
    while (i < chunkEnd) {
      if (counter.on) counter.n++;
      if (skippable && pos >= m.genStart && pos < m.genEnd) {
        pos = m.genEnd;
        i = m.chunkEnd;
        continue;
      }
      const chunk = chunks[i];
      if (!src.startsWith(chunk, pos + delta)) return false;
      pos += chunk.length;
      i++;
    }
    if (genEnd === f.generatedStart) return true;
    // A closing frame ends at the frontier: the memo overlaps it (the
    // range grows along a spine), or ends in a gap left of it, which
    // bridges into one range when the gap's chunks match too (the bytes
    // of marks that never verify, a synthetic `.` between two verified
    // ranges). An unbridgeable gap spends the old range: the frontier's
    // replaces it.
    if (m !== undefined && (f.generatedStart <= m.genEnd || bridges(chunks, m, f, delta, src))) {
      if (f.generatedStart < m.genStart) {
        m.genStart = f.generatedStart;
        m.chunkStart = f.chunkStart;
      }
      m.genEnd = genEnd;
      m.chunkEnd = chunkEnd;
    } else {
      this.exact.set(delta, { genStart: f.generatedStart, genEnd, chunkStart: f.chunkStart, chunkEnd });
    }
    return true;
  }

  // A layout twin: a cover frame of a normalized role whose source and
  // emission differ only in whitespace-run lengths, each non-space
  // segment verbatim by construction. The size gate keeps the join off
  // big covers, which are never twins.
  layoutTwin(f) {
    if (this.source === null) return;
    const srcLen = f.sourceEnd - f.sourceStart;
    const genLen = this.length - f.generatedStart;
    if (srcLen === 0 || genLen === 0 || srcLen > 256 || genLen > 256) return;
    const src = this.source.slice(f.sourceStart, f.sourceEnd);
    const gen = this.chunks.slice(f.chunkStart).join('');
    if (src.replace(/\s+/g, ' ') !== gen.replace(/\s+/g, ' ')) return;
    let si = 0, gi = 0;
    while (si < src.length && gi < gen.length) {
      if (/\s/.test(src[si])) {
        while (si < src.length && /\s/.test(src[si])) si++;
        while (gi < gen.length && /\s/.test(gen[gi])) gi++;
        continue;
      }
      let len = 0;
      while (si + len < src.length && !/\s/.test(src[si + len])) len++;
      this.rows.push({
        nodeId: f.nodeId, role: f.role, mappingKind: 'exact',
        sourceStart: f.sourceStart + si, sourceEnd: f.sourceStart + si + len,
        generatedStart: f.generatedStart + gi, generatedEnd: f.generatedStart + gi + len,
        fileId: 0,
      });
      si += len; gi += len;
    }
  }

  // Injected text with no source (a runtime unit, the schema intrinsic
  // block) records ONE synthetic row from `generatedStart` to here: a
  // zero-width source anchor at the program's start that reverse lookups
  // see and the source map never serializes.
  syntheticRow(programId, role, generatedStart) {
    if (programId === null || !this.record) return;
    this.rows.push({
      nodeId: programId, role, mappingKind: 'synthetic',
      sourceStart: 0, sourceEnd: 0,
      generatedStart, generatedEnd: this.offset,
      fileId: 0,
    });
  }
}

// Do the chunks between the memo range's end and frame `f`'s start match
// the source at `delta`? Stops at the first mismatch.
function bridges(chunks, m, f, delta, src) {
  let pos = m.genEnd;
  for (let i = m.chunkEnd; i < f.chunkStart; i++) {
    if (counter.on) counter.n++;
    const chunk = chunks[i];
    if (!src.startsWith(chunk, pos + delta)) return false;
    pos += chunk.length;
  }
  return true;
}
